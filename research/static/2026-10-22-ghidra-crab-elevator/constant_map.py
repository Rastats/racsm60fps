#!/usr/bin/env python3
"""Consolidate the existing LEVEL_01 30 Hz constant maps into one address -> role -> C1-risk table.

Inputs (all already in the repository, nothing is rescanned):
- research/v2/decomp-summary/level01-k30-context-audit.json: the 108 `lui 0x3D08` (1/30)
  sites with a call-context verdict;
- level01-class-updates.json: class -> pump-1 update;
- level01-frames30-sites.json (x30.0 conversions), level01-phase-steps.json (per-call
  fade/phase steps), LEVEL01-FRAME-TIMERS.md (integer frame timers): counted, not listed;
- tools/runtime/fixes.py DATA / ALIASES: which word-level fix already covers a site;
- optional: an entities.py / census JSON of a live state, to mark classes present there.

Output: CONSTANT-MAP.md next to this script (STATIC; verdicts are INFERRED by the audit).

Usage (from the repository root):
  python research/static/2026-10-22-ghidra-crab-elevator/constant_map.py \
      [--live D:/racsm60fps/work/runs/entities-pokitaru-blaster.json]
"""
import argparse
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DS = ROOT / 'research/v2/decomp-summary'
sys.path.insert(0, str(ROOT / 'tools/runtime'))
import fixes as fx  # noqa: E402

RISK = {
    'PER_CALL_CANDIDATE': 'HIGH: fixed 1/30 per update, runs 2x as often in C1, no fix yet',
    'DELTA_FUNCTION': 'LOW: function also reads the frame delta; check that 1/30 is not added per call',
    'SUBSTEP_ALREADY_CORRECT': 'NONE: player substep loop, already 60 calls/s in A0',
}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--live', type=Path, help='entities.py list JSON or census JSON of a live state')
    a = ap.parse_args()
    audit = json.loads((DS / 'level01-k30-context-audit.json').read_text(encoding='utf-8'))
    updates = json.loads((DS / 'level01-class-updates.json').read_text(encoding='utf-8'))['classes']
    by_update = {int(u['update'], 16): u['class'] for u in updates}
    live = set()
    if a.live:
        doc = json.loads(a.live.read_text(encoding='utf-8'))
        rows = doc.get('entities') or doc.get('groups') or []
        live = {by_update.get(int(r['callback'], 16)) for r in rows if r.get('callback')}
    data_sites = {rva: name for name, (rva, _o, _n) in fx.DATA.items()}
    verdicts = collections.Counter(s['verdict'] for s in audit['sites'])
    frames30 = json.loads((DS / 'level01-frames30-sites.json').read_text(encoding='utf-8'))['sites']
    phases = json.loads((DS / 'level01-phase-steps.json').read_text(encoding='utf-8'))['sites']

    out = ['# LEVEL_01 30 Hz constants: address -> role -> C1 risk (consolidated 2026-10-22)', '',
           'Status: STATIC. Consolidates existing maps; verdicts are the INFERRED call-context verdicts of',
           '`research/v2/decomp-summary/level01-k30-context-audit.json` (method in that file). Generated by',
           '`constant_map.py` beside this file' + (f'; live classes from `{a.live.name}`.' if a.live else '.'), '',
           '## 1/30 literals (`lui 0x3D08`, 108 sites)', '', '| Verdict | Sites | C1 risk |', '|---|---:|---|']
    for v, n in verdicts.most_common():
        out.append(f"| {v} | {n} | {RISK.get(v, 'covered by the named fix (word-level or plugin); measured only where noted')} |")
    out += ['', '### Open sites (PER_CALL_CANDIDATE, no fix)', '',
            '| Site | Function | Kind | Classes (live here: *) |', '|---|---|---|---|']
    for s in sorted(audit['sites'], key=lambda s: int(s['site'], 16)):
        if s['verdict'] != 'PER_CALL_CANDIDATE':
            continue
        cls = ', '.join(c + ('*' if c in live else '') for c in s['classes']) or '(engine / unknown)'
        out.append(f"| `{s['site']}` | `{s['fn']}` | {s['oldKind']} | {cls} |")
    covered30 = sum(1 for s in frames30 if int(s['site'], 16) in data_sites)
    ph = collections.Counter(s['verdict'] for s in phases)
    out += ['', '## Other 30 Hz shapes (counts; see the source files)', '',
            '| Shape | Count | Source / fix |', '|---|---:|---|',
            f'| `x 30.0` seconds -> frames (`lui 0x41F0`) | {len(frames30)} | `level01-frames30-sites.json`; fix `frames30` ({covered30} sites are DATA words) |',
            f"| per-call fade / phase steps | {len(phases)} ({ph.get('PATCH_CANDIDATE', 0)} candidates, {ph.get('EXCLUDED', 0)} excluded) | `level01-phase-steps.json`; fix `phases` |",
            '| integer frame timers (+-1 per update, literals in 30 Hz frames) | 23 classes/fields | `LEVEL01-FRAME-TIMERS.md`; Crab: `crabtimers` (+0x60 reloads, +0x64 cooldown) |',
            '| frame-counter clock users (`& 1`, `% n` on 0x2AF28C) | 19 pairs / 14 users | `level01-clock-sites.json`; fix `clock` |',
            '', '## Measured on the bench (2026-10-22, REPORT.md)', '',
            '- Crab attack threshold 27.0 at `0x2CF3C8` (`crab`): first-hit wind-up A0 0.9009 s, C1 0.8007 s, C1+crab 0.9008 s.',
            '- Crab decide/cooldown state 0xE (data+0x64 reloaded from trunc(helper x 15.0)): A0 0.5005 s, C1 0.2502 s,',
            '  C1+crab+crabtimers 0.5005 s.',
            '- Lvl3Elevator step (1/moveTime)*(1/30) at `0x1563E8` (`elevator`): A0 10.01 s, C1 5.005 s; the fix only acts',
            '  when the initializer runs (level creation).']
    (Path(__file__).parent / 'CONSTANT-MAP.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f"wrote CONSTANT-MAP.md: {verdicts['PER_CALL_CANDIDATE']} open 1/30 sites")


if __name__ == '__main__':
    main()
